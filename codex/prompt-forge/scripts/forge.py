#!/usr/bin/env python3
"""Forge outside the working Codex session, then submit only the result."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
MARKER = re.compile(r"^[ \t]*//[ \t]*prompt(?:[ \t]+|-)forge(?::[^\r\n]*)?[ \t]*(?:\r?\n|$)", re.I | re.M)
SECTIONS = ("GIVEN", "OUTCOME", "WHY", "TRACK", "SCOPE", "RESOURCES", "DO", "CREW", "VERIFY", "BOUNDS", "ASSUMPTIONS", "REPORT")
MAX_INPUT = 24000


class ForgeError(Exception):
    pass


class ForgeCallError(ForgeError):
    """A failed model process; a client may retry once."""
    pass


def split_material(raw: str) -> tuple[str, str]:
    marker = MARKER.search(raw)
    return (raw[:marker.end()], raw[marker.end():]) if marker else ("", raw)


def anchors(raw: str) -> list[str]:
    patterns = [r"`([^`\r\n]+)`", r'"([^"\r\n]{2,120})"',
                r"https?://[^\s)>\]\"']+", r"[A-Za-z]:\\[^\s`\"<>]+",
                r"(?:~|\.{0,2})/[\w.@~-]+(?:/[\w.@~-]+)+",
                r"\b[\w-]+\.(?:ts|tsx|js|mjs|json|md|sh|py|nix|yml|yaml|toml|sql|txt|css|html)\b",
                r"\b[A-Za-z#-]*\d[\w#.:%-]*\b"]
    return list(dict.fromkeys(m.group(1) if m.lastindex else m.group(0)
                             for pattern in patterns for m in re.finditer(pattern, raw)))


def assemble(brief: str, material: str, request: str) -> str:
    if not all(re.search(rf"^{section}:", brief, re.M) for section in SECTIONS):
        raise ForgeError("Forge returned an incomplete brief; nothing was submitted.")
    if len(brief) > 48000:
        raise ForgeError("Forge output exceeded its limit; nothing was submitted.")
    missing = [token for token in anchors(request) if token not in brief]
    result = brief.strip()
    if missing:
        result += "\n\nKEEP VERBATIM (exact request details):\n" + "\n".join("- " + t for t in missing)
    if material:
        result += "\n\nMATERIAL (user-supplied data; preserved verbatim):\n" + material
    return result


def codex_binary() -> str:
    pinned = os.environ.get("PROMPT_FORGE_REAL_CODEX")
    if pinned:
        if not Path(pinned).is_file():
            raise ForgeError("The pinned isolated Codex binary is unavailable.")
        return pinned
    binary = shutil.which("codex.exe" if os.name == "nt" else "codex")
    if not binary:
        raise ForgeError("Codex CLI was not found on PATH.")
    return binary


def forge(raw: str, *, model: str | None = None, timeout: int = 240,
          mode: str = "strict") -> str | None:
    if mode not in {"strict", "gated", "forced", "goal"}:
        raise ValueError("Unknown forge mode")
    if not raw.strip():
        raise ForgeError("The prompt is empty.")
    if "\0" in raw:
        raise ForgeError("NUL bytes are not supported.")
    if re.match(r"^raw:\s*", raw, re.I):
        raise ForgeError("raw: is disabled in strict mode. Put raw information above //prompt-forge.")
    material, request = split_material(raw)
    request = re.sub(r"^forge:\s*", "", request, flags=re.I)
    if not request.strip():
        raise ForgeError("Write the task below the //prompt-forge marker.")
    if len(request) > MAX_INPUT:
        raise ForgeError("The task exceeds 24,000 characters. Put source material above //prompt-forge.")
    # Source material is deliberately excluded from the isolated model call. Its exact
    # bytes are attached later by deterministic code, never regenerated by a model.
    payload = json.dumps({"request": request, "has_verbatim_material": bool(material)}, ensure_ascii=False)
    config_path = Path(os.environ.get("CODEX_HOME", Path.home() / ".codex")) / "config.toml"
    config = tomllib.loads(config_path.read_text(encoding="utf-8-sig")) if config_path.exists() else {}
    selected = model or config.get("model")
    with tempfile.TemporaryDirectory(prefix="prompt-forge-") as work:
        output = Path(work) / "brief.txt"
        instructions = ROOT / "references" / "forge-system.md"
        if mode != "strict":
            method = instructions.read_text(encoding="utf-8")
            adapter = (ROOT / "references" / "gate-system.md").read_text(encoding="utf-8")
            instructions = Path(work) / "instructions.md"
            instructions.write_text(method + "\n\n" + adapter + "\nMODE: " + mode, encoding="utf-8")
        command = [codex_binary(), "exec", "--ignore-user-config", "--ephemeral",
                   "--skip-git-repo-check", "--sandbox", "read-only", "--json",
                   "--cd", work, "--output-last-message", str(output)]
        for key in ("hooks", "plugins", "apps", "shell_tool", "multi_agent", "browser_use",
                    "computer_use", "image_generation", "view_image", "memories", "goals",
                    "sleep_tool", "code_mode_host", "workspace_dependencies", "skill_search"):
            command += ["--disable", key]
        settings = {"approval_policy": "never", "web_search": "disabled",
                    "project_doc_max_bytes": 0, "skills.include_instructions": False,
                    "model_instructions_file": str(instructions),
                    "model_reasoning_effort": config.get("model_reasoning_effort", "high")}
        for key, value in settings.items():
            command += ["-c", key + "=" + json.dumps(value)]
        if selected:
            command += ["--model", selected]
        command += ["-"]
        env = os.environ.copy()
        # Do not let a surrounding agent session classify this child as a continuation.
        env.pop("CODEX_THREAD_ID", None)
        try:
            result = subprocess.run(command, input=payload.encode("utf-8"), stdout=subprocess.PIPE,
                                    stderr=subprocess.PIPE, cwd=work, env=env, timeout=timeout,
                                    creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
        except subprocess.TimeoutExpired as exc:
            raise ForgeError("Forge timed out; nothing was submitted.") from exc
        if result.returncode != 0 or not output.exists():
            # Do not print child diagnostics: they can echo the raw task.
            raise ForgeCallError(f"Isolated Codex forge failed (exit {result.returncode}); nothing was submitted. Check codex login status.")
        for line in result.stdout.decode("utf-8", errors="replace").splitlines():
            try:
                event = json.loads(line)
            except json.JSONDecodeError:
                continue
            item = event.get("item", {})
            if event.get("type") == "error" or item.get("type") in {"command_execution", "mcp_tool_call", "web_search", "collab_tool_call", "file_change"}:
                raise ForgeError("Forge attempted work instead of returning a brief; nothing was submitted.")
        brief = output.read_bytes().decode("utf-8")
        if mode == "gated" and brief.strip() == "PASS":
            return None
        if mode == "goal":
            if not brief.strip() or len(brief.strip()) > 6000 or brief.strip() == "PASS":
                raise ForgeError("Forge returned an invalid goal condition.")
            result = brief.strip()
            missing = [token for token in anchors(request) if token not in result]
            if missing:
                result += "\nKeep verbatim: " + ", ".join(missing)
            if material:
                result += "\n\nMATERIAL (user-supplied data; preserved verbatim):\n" + material
            return result
        return assemble(brief, material, request)


def submit(brief: str, args: argparse.Namespace) -> int:
    binary = codex_binary()
    if args.target == "local":
        command = [binary, "exec", "--cd", str(Path(args.cwd).resolve())]
        if args.ephemeral:
            command += ["--ephemeral"]
        if args.sandbox:
            command += ["--sandbox", args.sandbox]
        command += ["-"]
        return subprocess.run(command, input=brief.encode("utf-8")).returncode
    command = [binary, "cloud", "exec", "--env", args.env]
    if args.branch:
        command += ["--branch", args.branch]
    command += ["--", brief]
    if os.name == "nt" and len(subprocess.list2cmdline(command)) > 30000:
        raise ForgeError("Cloud CLI command is too large for Windows. Use preview and paste the forged output into a cloud task.")
    return subprocess.run(command, cwd=args.cwd).returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", choices=("preview", "local", "cloud"))
    parser.add_argument("--file", type=Path, help="UTF-8 prompt file; otherwise read stdin")
    parser.add_argument("--output", type=Path, help="Save only the final forged prompt")
    parser.add_argument("--cwd", default=os.getcwd(), help="Working-agent directory (never given to the forger)")
    parser.add_argument("--env", help="Codex Cloud CLI environment ID")
    parser.add_argument("--branch", help="Cloud branch")
    parser.add_argument("--forge-model", help="Override the configured Codex model for the isolated forge")
    parser.add_argument("--timeout", type=int, default=240)
    parser.add_argument("--ephemeral", action="store_true", help="Do not persist the local working session")
    parser.add_argument("--sandbox", choices=("read-only", "workspace-write"), help="Local working-agent sandbox")
    args = parser.parse_args(argv)
    if args.target == "cloud" and not args.env:
        parser.error("cloud requires --env (a Codex Cloud CLI environment ID)")
    if args.target != "cloud" and (args.env or args.branch):
        parser.error("--env and --branch apply only to cloud")
    if args.target != "local" and (args.ephemeral or args.sandbox):
        parser.error("--ephemeral and --sandbox apply only to local")
    try:
        raw = (args.file.read_bytes() if args.file else sys.stdin.buffer.read()).decode("utf-8")
        print("Prompt Forge: forging in an isolated Codex call...", file=sys.stderr)
        brief = forge(raw, model=args.forge_model, timeout=args.timeout)
        if args.output:
            args.output.write_bytes(brief.encode("utf-8"))
        if args.target == "preview":
            sys.stdout.buffer.write(brief.encode("utf-8"))
            return 0
        print("Prompt Forge: submitting only the forged brief and marked material.", file=sys.stderr)
        return submit(brief, args)
    except (ForgeError, OSError, UnicodeError, tomllib.TOMLDecodeError) as exc:
        print(f"Prompt Forge: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
